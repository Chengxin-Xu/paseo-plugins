// Precomputes the palettes clients register at connect time, so the resident client stub carries colours, not the
// OKLCH recipe that derives them: the twelve fixed themes (shared/palette.ts) and the custom slot's default palette
// (shared/custom.ts), shown until the host's copy arrives. tests/generated.test.ts fails when the file is stale.
// Usage: npm run generate (writes shared/generated/themes.ts)
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUTPUT = join(root, "shared/generated/themes.ts");

/** The generated module's text. */
export async function render() {
  const { THEMES } = await import(join(root, "shared/palette.ts"));
  const { customPalette } = await import(join(root, "shared/custom.ts"));
  const { DEFAULT_CUSTOM, PALETTE_TOKENS } = await import(join(root, "shared/params.ts"));
  const hexes = (colors) =>
    PALETTE_TOKENS.map((token) => {
      const hex = colors[token];
      if (!/^#[0-9A-F]{6}$/.test(hex)) throw new Error(`${token} is not an upper-case #RRGGBB colour: ${hex}`);
      return hex.slice(1);
    }).join(" ");
  const fallback = customPalette(DEFAULT_CUSTOM);
  const row = (entry) => {
    for (const field of [entry.id, entry.name]) if (/[|\n`$\\]/.test(field)) throw new Error(`cannot put ${JSON.stringify(field)} in the table`);
    return `${entry.id}|${entry.name}|${entry.appearance}|${hexes(entry.colors)}`;
  };
  const lines = [
    "// Generated by scripts/generate-themes.mjs from shared/palette.ts and shared/custom.ts; run `npm run generate` after",
    "// changing either. tests/generated.test.ts checks that this file is current.",
    'import type { PluginThemeColors, PluginThemeContribution } from "@getpaseo/plugin";',
    'import { PALETTE_TOKENS, type Appearance, type CustomPalette } from "../params.ts";',
    "",
    "/** Eight colours in `PALETTE_TOKENS` order, as `RRGGBB` separated by spaces. */",
    "function colors(list: string): PluginThemeColors {",
    '  const hexes = list.split(" ");',
    "  const result: Record<string, string> = {};",
    "  PALETTE_TOKENS.forEach((token, index) => {",
    "    result[token] = `#${hexes[index]}`;",
    "  });",
    "  return result as unknown as PluginThemeColors;",
    "}",
    "",
    "/** One fixed theme per line: id|name|appearance|colours. */",
    "const TABLE = `" + THEMES.map(row).join("\n") + "`;",
    "",
    "/** The twelve fixed themes, as `paletteFor` derives them. */",
    'export const FIXED_THEMES: readonly PluginThemeContribution[] = TABLE.split("\\n").map((line) => {',
    '  const [id, name, appearance, list] = line.split("|") as [string, string, Appearance, string];',
    "  return { id, name, appearance, colors: colors(list) };",
    "});",
    "",
    "/** The custom slot at its default parameters: what the slot shows until the host answers. */",
    `export const DEFAULT_PALETTE: CustomPalette = { appearance: ${JSON.stringify(fallback.appearance)}, colors: colors("${hexes(fallback.colors)}") };`,
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUTPUT, await render());
  console.log(`wrote ${OUTPUT}`);
}
