import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// The installed UI is served from server/generated, not rebuilt by `paseo plugin reload`.
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const chunks = JSON.parse(await readFile(join(root, "client-chunks.json"), "utf8"));
for (const { name, entry, manifest, api } of chunks) {
  const result = await build({
    absWorkingDir: root, entryPoints: [entry], bundle: true, write: false, platform: "browser", format: "cjs",
    target: "es2020", jsx: "automatic", packages: "external", minifyWhitespace: true, minifySyntax: true,
    legalComments: "none", logLevel: "warning",
    plugins: [{ name: "client-boundary", setup(builder) {
      builder.onResolve({ filter: /^(?:node:)|(?:^|\/)server\// }, args => ({ errors: [{ text: `Server-only import in client chunk: ${args.path}` }] }));
    } }],
  });
  const code = `(function(require) {\nconst module = { exports: {} };\nconst exports = module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;\n})\n`;
  const metadata = { name, hash: createHash("sha256").update(code).digest("hex").slice(0, 16), api, bytes: Buffer.byteLength(code) };
  await writeFile(join(root, "server", "generated", `${name}-chunk.txt`), code);
  await writeFile(join(root, "shared", "generated", `${name}-chunk-manifest.ts`),
    `// Generated by scripts/build-client-chunks.mjs; do not edit.\nexport const ${manifest} = ${JSON.stringify(metadata)} as const;\n`);
  console.log(`Built ${name}: ${metadata.bytes} bytes (${metadata.hash})`);
}
